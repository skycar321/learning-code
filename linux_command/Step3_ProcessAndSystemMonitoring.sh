#!/bin/bash

# Linux 명령어 학습 계획 - 3단계: 프로세스 관리 및 시스템 모니터링
# 이 스크립트는 Linux 시스템에서 실행되는 프로세스를 이해하고 제어하며,
# 시스템 자원 사용량을 모니터링하는 명령어를 학습하기 위한 예시들을 포함하고 있습니다.
#
# 프로세스 관리 및 시스템 모니터링은 서버의 안정성과 성능을 유지하는 데 필수적인 기술입니다.

echo "--- 3단계: 프로세스 관리 및 시스템 모니터링 ---"

# -----------------------------------------------------------------------------
# 1. 프로세스 이해 (Understanding Processes)
# - 프로세스: 실행 중인 프로그램의 인스턴스.
# - PID (Process ID): 각 프로세스에 할당되는 고유 번호.
# - PPID (Parent Process ID): 프로세스를 실행한 부모 프로세스의 PID.
# - 상태: R (실행 중), S (대기 중), Z (좀비), T (정지), D (인터럽트 불가 슬립)
# -----------------------------------------------------------------------------
echo "1. 프로세스 이해 및 정보 확인 (개념적 설명)"
echo "  모든 프로그램이 실행될 때 프로세스가 생성되며, 각 프로세스는 고유한 ID를 가집니다."
echo "  프로세스들은 트리 구조를 가지며, 부모-자식 관계를 통해 관리됩니다."
echo ""

# -----------------------------------------------------------------------------
# 2. 프로세스 모니터링
# -----------------------------------------------------------------------------
echo "2.1. `ps` - 현재 실행 중인 프로세스 목록 출력:"
echo "  `ps aux`: 모든 사용자의 프로세스를 상세하게 출력"
ps aux | head -n 5 # 상위 5줄만 출력
echo "  `ps -ef`: 모든 프로세스를 트리 형태로 출력 (자세한 정보)"
echo "  `ps -p <PID>`: 특정 PID의 프로세스 정보 출력"
echo ""

echo "2.2. `top` - 실시간 프로세스 모니터링:"
echo "  `top` 명령은 CPU, 메모리 사용량 등 프로세스 정보를 실시간으로 업데이트하여 보여줍니다."
echo "  이 스크립트에서는 `top`을 직접 실행하지 않고 개념만 설명합니다. (종료하려면 'q' 누름)"
echo "  `top -bn1 | head -n 5`: `top` 명령의 현재 스냅샷을 한 번만 찍어 출력"
top -bn1 | head -n 5
echo "  주요 정보: PID, USER, %CPU, %MEM, VIRT, RES, SHR, S (상태), TIME+, COMMAND"
echo ""

echo "2.3. `htop` - `top`의 개선된 버전 (설치 필요):"
echo "  `htop`은 `top`보다 더 사용자 친화적인 인터페이스와 기능을 제공합니다."
echo "  설치: `sudo apt install htop` (Ubuntu), `sudo yum install htop` (CentOS)"
echo "  이 스크립트에서는 `htop`을 직접 실행하지 않고 개념만 설명합니다."
echo ""

# -----------------------------------------------------------------------------
# 3. 프로세스 제어 (Process Control)
# -----------------------------------------------------------------------------
echo "3.1. `kill` - 프로세스 종료:"
# `kill <PID>`: 기본적으로 SIGTERM (종료 요청) 신호를 보냅니다.
# `kill -9 <PID>`: SIGKILL (강제 종료) 신호를 보냅니다. 프로세스가 즉시 종료되며 정리 작업을 할 수 없습니다.
echo "  `kill` 명령은 프로세스에 신호(signal)를 보내어 제어합니다."
echo "  종료 테스트를 위해 백그라운드 프로세스 실행:"
sleep 100 & # 100초 동안 대기하는 프로세스를 백그라운드로 실행
SLEEP_PID=$! # 백그라운드 프로세스의 PID를 변수에 저장
echo "  `sleep 100` 프로세스 (PID: $SLEEP_PID)가 시작되었습니다."
echo "  3초 후 종료 시도..."
sleep 3
kill $SLEEP_PID
echo "  `sleep` 프로세스에 SIGTERM 신호를 보냈습니다."
# sleep 프로세스는 SIGTERM을 받으면 정상적으로 종료됩니다.
sleep 1 # 프로세스 종료 대기
ps -p $SLEEP_PID | grep $SLEEP_PID # 프로세스 존재 여부 확인
if [ $? -eq 0 ]; then
    echo "  프로세스 $SLEEP_PID 가 아직 실행 중입니다. 강제 종료 (SIGKILL) 시도."
    kill -9 $SLEEP_PID
    echo "  프로세스 $SLEEP_PID 강제 종료."
fi
echo ""

echo "3.2. `killall` - 이름으로 프로세스 종료:"
# `killall <process-name>`: 특정 이름을 가진 모든 프로세스를 종료합니다. (주의해서 사용)
echo "  `killall`은 특정 이름을 가진 모든 프로세스를 종료합니다."
# `killall firefox` # 예시: 모든 Firefox 프로세스 종료
echo ""

# -----------------------------------------------------------------------------
# 4. 백그라운드 작업 (Background Jobs)
# - 터미널을 점유하지 않고 작업을 실행하는 방법.
# -----------------------------------------------------------------------------
echo "4.1. `&` - 명령어를 백그라운드로 실행:"
echo "  `sleep 5 &` (5초 대기 후 종료되는 프로세스를 백그라운드로 실행)"
sleep 5 &
echo "  백그라운드에서 `sleep 5` 프로세스가 시작되었습니다."
echo ""

echo "4.2. `jobs` - 백그라운드 작업 목록 확인:"
jobs
echo ""

echo "4.3. `fg` / `bg` - 백그라운드 작업을 포그라운드/백그라운드로 전환:"
# `fg %<job-number>`: 백그라운드 작업을 포그라운드로 전환.
# `bg %<job-number>`: 정지된 백그라운드 작업을 다시 백그라운드에서 실행.
# 나쁜 예시: `jobs` 명령으로 작업 번호를 확인하지 않고 `fg`를 사용하여
# - 여러 백그라운드 작업 중 의도하지 않은 작업을 포그라운드로 가져오는 것.
echo ""

echo "4.4. `nohup` - 터미널 종료 후에도 프로세스 유지:"
# `nohup command &`: 터미널 세션이 끊어져도 프로세스가 계속 실행되도록 합니다.
echo "  `nohup sleep 10 &` (10초 대기 프로세스를 `nohup`으로 백그라운드 실행)"
nohup sleep 10 > /dev/null 2>&1 & # 출력을 /dev/null로 리다이렉션
NOHUP_PID=$!
echo "  `nohup sleep 10` 프로세스 (PID: $NOHUP_PID)가 시작되었습니다."
echo "  3초 후 `kill`로 종료 시도..."
sleep 3
kill $NOHUP_PID
echo "  `nohup` 프로세스 종료."
echo ""

# -----------------------------------------------------------------------------
# 5. 시스템 자원 확인 (System Resource Monitoring)
# -----------------------------------------------------------------------------
echo "5.1. `df` - 디스크 사용량 확인 (Disk Free):"
echo "  `df -h`: 디스크 사용량을 사람이 읽기 쉬운 형태로 출력"
df -h | head -n 5
echo ""

echo "5.2. `du` - 디렉토리 파일 사용량 확인 (Disk Usage):"
mkdir test_du > /dev/null 2>&1
echo "file1" > test_du/file1.txt
echo "file2" >> test_du/file2.txt
echo "long content" > test_du/long_file.txt
du -sh test_du # test_du 디렉토리의 전체 크기를 사람이 읽기 쉬운 형태로 출력
echo ""
rm -rf test_du > /dev/null 2>&1

echo "5.3. `free` - 메모리 사용량 확인:"
echo "  `free -h`: 메모리 사용량을 사람이 읽기 쉬운 형태로 출력"
free -h
echo ""

echo "5.4. `uptime` - 시스템 가동 시간 및 평균 부하 확인:"
uptime
echo "  `uptime`은 시스템이 얼마나 오래 작동했는지, 그리고 지난 1분, 5분, 15분 동안의 평균 부하를 보여줍니다."
echo ""

echo "--- 3단계 학습 완료 ---"
echo ""
