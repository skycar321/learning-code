// nodejs/Step3_WebServerAndRESTAPI/middleware/logger.js
// Node.js 학습 계획 - 3단계: 웹 서버 구축 및 REST API
// 이 파일은 Express.js 미들웨어를 사용하여 들어오는 요청을 로깅하는 `loggerMiddleware`입니다.
//
// 미들웨어는 Express.js의 핵심 기능 중 하나로,
// 요청-응답 주기 동안 특정 작업을 수행하여 공통 로직을 처리하는 데 사용됩니다.

// -----------------------------------------------------------------------------
// 학습 포인트 1: Express.js 미들웨어 함수 정의
// - `(req, res, next)` 세 가지 인자를 받는 함수로 정의됩니다.
//   - `req`: HTTP 요청 객체.
//   - `res`: HTTP 응답 객체.
//   - `next`: 다음 미들웨어 또는 라우트 핸들러를 호출하는 함수.
// -----------------------------------------------------------------------------
function loggerMiddleware(req, res, next) {
    // -----------------------------------------------------------------------------
    // 학습 포인트 2: 요청 정보 로깅
    // - `req.method`: 요청 HTTP 메서드 (GET, POST 등).
    // - `req.url`: 요청 URL.
    // - `new Date().toISOString()`: 요청이 들어온 시간.
    // -----------------------------------------------------------------------------
    console.log(`[${new Date().toISOString()}] ${req.method} ${req.url}`);

    // 나쁜 예시: 미들웨어에서 `next()`를 호출하지 않는 것.
    // - `next()`를 호출하지 않으면 요청이 미들웨어 체인에서 멈추고,
    // - 라우트 핸들러가 호출되지 않아 클라이언트가 응답을 받지 못하게 됩니다 (요청이 대기 상태).
    next(); // 다음 미들웨어 또는 라우트 핸들러로 요청 전달
}

// -----------------------------------------------------------------------------
// 학습 포인트 3: `module.exports`를 이용한 미들웨어 내보내기
// - 이 미들웨어 함수를 `server.js`에서 `app.use()`로 등록할 수 있도록 내보냅니다.
// -----------------------------------------------------------------------------
module.exports = loggerMiddleware;

