#!/bin/bash

# Jenkins 학습 계획 - 3단계: Jenkins Job 구성 (빌드 스크립트 예시)
# 이 스크립트는 Jenkins Pipeline에서 호출될 수 있는 간단한 빌드 스크립트입니다.
# 실제 프로젝트에서는 Maven, Gradle, Node.js 등의 빌드 명령어를 포함하게 됩니다.

echo "--- Jenkins 빌드 스크립트 시작 ---"

# -----------------------------------------------------------------------------
# 1. 빌드 환경 확인
# - Jenkinsfile에서 설정된 환경 변수나 도구가 올바르게 인식되는지 확인합니다.
# -----------------------------------------------------------------------------
echo "현재 작업 디렉토리: $(pwd)"
echo "Git Rev: $(git rev-parse HEAD)" # Jenkinsfile의 `git` 스텝이 실행된 후 가능
echo "Java Version (예상): $JAVA_HOME/bin/java -version" # Jenkins Global Tool Configuration에서 설정된 경우

# -----------------------------------------------------------------------------
# 2. 의존성 설치
# - 프로젝트의 종류에 따라 필요한 의존성(dependency)을 설치합니다.
# -----------------------------------------------------------------------------
echo "2. 의존성 설치"
# Maven 프로젝트 예시
# mvn clean install -DskipTests
# Gradle 프로젝트 예시
# ./gradlew clean build -x test
# Node.js 프로젝트 예시
# npm install
# echo "프로젝트 의존성 설치 완료."

# 이 예시에서는 간단한 텍스트 파일을 생성하여 빌드 결과물 시뮬레이션
echo "간단한 빌드 결과물을 생성합니다."
echo "Build result from Jenkins Pipeline" > build_output.txt
echo "Version: 1.0.0" >> build_output.txt
echo "Build Timestamp: $(date)" >> build_output.txt

# -----------------------------------------------------------------------------
# 3. 컴파일 및 패키징
# - 소스 코드를 컴파일하고 실행 가능한 아티팩트(JAR, WAR 등)로 패키징합니다.
# -----------------------------------------------------------------------------
echo "3. 컴파일 및 패키징"
# 실제 프로젝트에서는 여기에서 컴파일 및 패키징 명령어를 실행합니다.
# 예시:
# mvn package
# ./gradlew assemble
# npm run build
echo "컴파일 및 패키징 완료. (build_output.txt 파일 생성)"

# 빌드 결과물 (아티팩트)을 특정 디렉토리에 저장 (Jenkinsfile의 archiveArtifacts 스텝에서 사용)
mkdir -p build/libs
cp build_output.txt build/libs/my-app-1.0.0.jar # JAR 파일처럼 보이도록 확장자만 변경 (시뮬레이션)
echo "빌드 결과물이 'build/libs/my-app-1.0.0.jar'로 생성되었습니다."

# -----------------------------------------------------------------------------
# 4. 정적 코드 분석 (선택 사항)
# - SonarQube Scanner 등을 사용하여 코드 품질을 분석하고 기술 부채를 확인합니다.
# -----------------------------------------------------------------------------
echo "4. 정적 코드 분석 (선택 사항)"
# sonar-scanner // SonarQube 연동 예시
echo "정적 코드 분석을 수행했습니다."

echo "--- Jenkins 빌드 스크립트 종료 ---"

# 나쁜 예시: 빌드 스크립트 내에서 에러 처리 없이 명령어를 실행하여
# - 작은 오류에도 빌드가 실패하게 만들거나, 중요한 단계를 건너뛰게 하는 것.
# - 항상 명령어 실행 후 반환 코드($?)를 확인하여 오류를 감지하고 적절히 대응해야 합니다.
# 좋은 예시: `set -e`를 스크립트 시작 부분에 추가하여 어떤 명령어가 실패하면
# - 즉시 스크립트를 종료하도록 설정하거나, `try-catch`와 유사한 방식으로 에러를 처리합니다.
